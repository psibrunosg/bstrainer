// ponytail: hand-rolled SW for the static app shell. Navigations are
// network-first (so deploys aren't stuck behind a stale cached shell);
// hashed static assets and the exercise catalog are cache-first.
// No push notifications / background sync — future phases, add as separate
// event listeners here when needed.
const CACHE_VERSION = "v2";
const CACHE_NAME = `bstrainer-shell-${CACHE_VERSION}`;

self.addEventListener("install", () => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.href.includes("supabase")) return; // API calls must always hit network

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const clone = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, clone));
          }
          return response;
        })
        .catch(() => caches.match(request))
    );
    return;
  }

  const isCacheFirst = url.pathname.includes("/_next/static/") || url.pathname.endsWith("/exercises.json");
  if (!isCacheFirst) return;

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response.ok) {
          const clone = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, clone));
        }
        return response;
      });
    })
  );
});
